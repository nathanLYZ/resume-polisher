  "⺽": "臼", "⺾": "艹", "⺿": "艹", "⻀": "艹", "⻁": "虎", "⻂": "衤",
  "⻃": "西", "⻄": "西", "⻅": "见", "⻆": "角", "⻇": "角", "⻈": "讠",
