/** 把部首码位的字形换成汉字（⻓期 → 长期） */
export function fixRadicals(t: string): string {
  return t.replace(/[\u2E80-\u2EF3]/g, (c) => RADICAL_TO_HANZI[c] ?? c);
}

/**
 * 清洗提取出来的简历文字：
 * 1. 部首码位还原 + NFKC 归一（康熙部首 ⼯→工、全角→半角）
 * 2. 去掉中文之间的排版空格（"个 人 简 介" → "个人简介"），中英之间的保留
 * 3. 压缩多余空格与空行，逐行 trim
 */
export function tidyExtractedText(raw: string): string {
  let t = fixRadicals(raw.normalize("NFKC"));
  t = t.replace(/\r\n?/g, "\n");
  t = t.replace(/[ \t]{2,}/g, " ");
  t = t.replace(
    /(?<=[\u3400-\u9FFF\uF900-\uFAFF\u3000-\u303F\uFF00-\uFFEF])[ ]+(?=[\u3400-\u9FFF\uF900-\uFAFF\u3000-\u303F\uFF00-\uFFEF])/g,
    ""
  );
  t = t
    .split("\n")
    .map((l) => l.trim())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
  return t.trim();
}
